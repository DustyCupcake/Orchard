"use client";

import { useMemo, useState } from "react";
import {
  createEmptyLane,
  describeLaneConsequence,
  laneAddress,
  laneRoute,
  LANE_PRESETS,
  normalizeLaneRule,
  validateLanes,
  type AdmissionLaneRule,
} from "@/lib/recruitment/lane-rules";
import { Button, Select, Toggle } from "./LaneEditorControls";

// docs/plans/admission-flow.md §3: the lanes appear as a short list of cards, each
// with a name, a one-line generated sentence and an Edit button; Edit opens a
// panel that runs top to bottom, and a question appears only once the earlier
// answers make it meaningful. The sentence under every lane is generated by
// the same function that decides a person's path (lane-rules), so the screen
// cannot describe something the system does not do.
//
// This is the one part of the settings screen that has to be a client
// component: a sentence that only appears after a save is a changelog, not a
// consequence. Everything is held in state and submitted as one JSON field,
// because the lane list is a whole — a lane can be added, edited and removed
// in one go, and the server validates the set, not the pieces.
//
// Imports only the pure half of the lane model (lane-rules), which has no
// runtime dependency on the database.
type Lane = AdmissionLaneRule & { key: string };

export type EventLaneSet = { id: string; label: string; laneIds: string[] };

let counter = 0;
const withKey = (rule: AdmissionLaneRule): Lane => ({ ...rule, key: rule.id ?? `new-${++counter}` });
const bare = ({ key, ...rule }: Lane): AdmissionLaneRule => {
  void key;
  return rule;
};

const field =
  "rounded-[var(--radius-md)] border border-[var(--border)] bg-[var(--surface)] px-2.5 py-1.5 text-[length:var(--text-body)] text-[var(--text)] focus:border-[var(--accent-1)] focus:outline-none";
const labelCls = "text-[length:var(--text-meta)] font-medium text-[var(--text-muted)]";
const hintCls = "text-[length:var(--text-meta)] text-[var(--text-muted)]";

export default function AdmissionLaneEditor({
  initial,
  eventSets,
}: {
  initial: AdmissionLaneRule[];
  /** Live events that have chosen their own set of open lanes — every one of
   *  them has to stay valid when the lanes change. */
  eventSets: EventLaneSet[];
}) {
  const [lanes, setLanes] = useState<Lane[]>(() => initial.map(withKey));
  const [editing, setEditing] = useState<string | null>(null);
  const [showPresets, setShowPresets] = useState(false);

  const problems = useMemo(
    () =>
      validateLanes(lanes.map(bare), [
        { label: "the community", laneIndexes: lanes.map((l, i) => (l.openInCommunity ? i : -1)).filter((i) => i >= 0) },
        ...eventSets.map((e) => ({
          label: `the event “${e.label}”`,
          laneIndexes: lanes.map((l, i) => (l.id && e.laneIds.includes(l.id) ? i : -1)).filter((i) => i >= 0),
        })),
      ]),
    [lanes, eventSets],
  );

  const update = (key: string, patch: Partial<AdmissionLaneRule>) =>
    setLanes((prev) => prev.map((l) => (l.key === key ? { ...normalizeLaneRule({ ...l, ...patch }), key } : l)));

  const addLane = (kind: "invite" | "public") => {
    const lane = withKey({ ...createEmptyLane(kind), name: "" });
    setLanes((prev) => [...prev, lane]);
    setEditing(lane.key);
  };

  const applyPreset = (key: string) => {
    const preset = LANE_PRESETS.find((p) => p.key === key);
    if (!preset) return;
    // The lanes already there are archived by the save (nothing is deleted,
    // and people in the funnel keep the path they entered on); the preset's
    // lanes are new. A preset lane that matches a current lane by name keeps
    // that lane's identity, so a community isn't made to start over for
    // choosing the shape it already has.
    const current = new Map(lanes.map((l) => [l.name.toLowerCase(), l]));
    setLanes(
      preset.lanes.map((rule) => {
        const same = current.get(rule.name.toLowerCase());
        return withKey(same?.id ? { ...rule, id: same.id } : rule);
      }),
    );
    setEditing(null);
    setShowPresets(false);
  };

  return (
    <div className="flex flex-col gap-3">
      <input type="hidden" name="lanes" value={JSON.stringify(lanes.map(bare))} />

      {lanes.length === 0 && (
        <p className="text-[length:var(--text-body)] text-[var(--text)]">
          No lanes — nobody can arrive. That&rsquo;s a valid choice for a community that isn&rsquo;t recruiting.
        </p>
      )}

      <div className="flex flex-col gap-3">
        {lanes.map((lane) => (
          <div key={lane.key} className="rounded-[var(--radius-md)] border border-[var(--border)] bg-[var(--surface)] p-4">
            <div className="flex flex-wrap items-baseline justify-between gap-2">
              <div className="flex items-baseline gap-2">
                <h3 className="text-[length:var(--text-heading)] font-medium text-[var(--text)]">{lane.name || "Unnamed lane"}</h3>
                <span className={labelCls}>{lane.kind === "invite" ? "invite lane" : `public lane · ${laneAddress(lane)}`}</span>
              </div>
              <div className="flex items-center gap-2">
                <Button onClick={() => setEditing(editing === lane.key ? null : lane.key)}>
                  {editing === lane.key ? "Done" : "Edit"}
                </Button>
              </div>
            </div>
            <p className="mt-1 max-w-[640px] text-[length:var(--text-body)] text-[var(--text)]">{describeLaneConsequence(lane)}</p>

            {editing === lane.key && <LanePanel lane={lane} onChange={(patch) => update(lane.key, patch)} onRemove={() => {
              setLanes((prev) => prev.filter((l) => l.key !== lane.key));
              setEditing(null);
            }} />}
          </div>
        ))}
      </div>

      {problems.length > 0 && (
        <div role="alert" className="rounded-[var(--radius-md)] border border-[var(--warning-border)] p-3" style={{ background: "var(--warning-soft)" }}>
          <p className="text-[length:var(--text-meta)] font-medium text-[var(--text)]">This can&rsquo;t be saved yet</p>
          <ul className="mt-1 list-disc pl-5 text-[length:var(--text-body)] text-[var(--text)]">
            {problems.map((p) => (
              <li key={p}>{p}</li>
            ))}
          </ul>
        </div>
      )}

      <div className="flex flex-wrap items-center gap-2">
        <Button onClick={() => addLane("invite")}>Add invite lane</Button>
        <Button onClick={() => addLane("public")}>Add public lane</Button>
        <Button onClick={() => setShowPresets((v) => !v)}>Start from a preset</Button>
      </div>

      {showPresets && (
        <div className="rounded-[var(--radius-md)] border border-dashed border-[var(--border)] p-3">
          <p className={labelCls}>Starting points, not modes</p>
          <p className={`${hintCls} mt-1 max-w-[560px]`}>
            Choosing one replaces the list above with its lanes. The lanes you have now are archived rather than
            deleted, and anyone already in the process keeps the path they entered on. Nothing is saved until you
            press Save.
          </p>
          <ul className="mt-2 flex flex-col gap-2">
            {LANE_PRESETS.map((preset) => (
              <li key={preset.key} className="flex flex-wrap items-center gap-3">
                <Button onClick={() => applyPreset(preset.key)}>{preset.label}</Button>
                <span className={hintCls}>{preset.blurb}</span>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

function LanePanel({
  lane,
  onChange,
  onRemove,
}: {
  lane: Lane;
  onChange: (patch: Partial<AdmissionLaneRule>) => void;
  onRemove: () => void;
}) {
  const route = laneRoute(lane);
  const isCheck = lane.verification === "community_check";
  const hasProcess = route === "process";

  return (
    <div className="mt-3 flex flex-col gap-4 border-t border-dashed border-[var(--border)] pt-3">
      {/* 1. Name and who it's for */}
      <section className="flex flex-col gap-2">
        <label className="flex flex-col gap-1">
          <span className={labelCls}>Name</span>
          <input className={field} value={lane.name} onChange={(e) => onChange({ name: e.target.value })} placeholder="e.g. Knows them personally" />
        </label>
        <Select
          label="Who arrives this way?"
          value={lane.kind}
          onChange={(value) => onChange({ kind: value as "invite" | "public" })}
          options={[
            { value: "invite", label: "People a member invites" },
            { value: "public", label: "People who find the community's application link" },
          ]}
        />
      </section>

      {/* 2. How they arrive */}
      {lane.kind === "invite" ? (
        <section className="flex flex-col gap-1">
          <p className={labelCls}>Which invitations does this lane take?</p>
          <Toggle label="From a member who knows them personally" checked={lane.handlesKnowsPersonally} onChange={(v) => onChange({ handlesKnowsPersonally: v })} />
          <Toggle label="From a member who thinks they'd fit (and doesn't claim to know them)" checked={lane.handlesGoodFitOnly} onChange={(v) => onChange({ handlesGoodFitOnly: v })} />
          <Toggle label="From a member who made neither mark" checked={lane.handlesNeither} onChange={(v) => onChange({ handlesNeither: v })} />
          <p className={hintCls}>
            The inviter is always asked, and what they say is shown to the people who evaluate — even where the
            lanes don&rsquo;t use it to choose a path. Each kind of invite belongs to exactly one lane.
          </p>
        </section>
      ) : (
        <section className="flex flex-col gap-1">
          <label className="flex flex-col gap-1">
            <span className={labelCls}>Address</span>
            <input className={field} value={lane.publicSlug ?? ""} onChange={(e) => onChange({ publicSlug: e.target.value })} placeholder="leave blank for /apply" />
          </label>
          <p className={hintCls}>
            Served at <strong>{laneAddress(lane)}</strong>. The first lane is at /apply and the others at /apply/&lt;name&gt;;
            each is its own starting point with its own process.
          </p>
        </section>
      )}

      {/* 3. What they go through */}
      <section className="flex flex-col gap-2">
        <Select
          label="Before they're admitted"
          value={lane.verification}
          onChange={(value) => onChange({ verification: value as "none" | "community_check" })}
          options={[
            { value: "none", label: "An application and/or an interview (or nothing at all)" },
            { value: "community_check", label: "Announce them to the community, and let anyone raise a concern" },
          ]}
        />
        {isCheck ? (
          <p className={hintCls}>
            The check is the whole process, so there is no application or interview here. Any member can raise a
            concern; a concern is never dropped on a timer — the mediation team talks it through, and unless they
            agree it&rsquo;s resolved, the arrival is held.
          </p>
        ) : (
          <div className="flex flex-col gap-1">
            <Toggle label="Ask for an application" checked={lane.applicationRequired} onChange={(v) => onChange({ applicationRequired: v })} />
            <Toggle label="Hold an interview" checked={lane.interviewRequired} onChange={(v) => onChange({ interviewRequired: v })} />
            {!lane.applicationRequired && !lane.interviewRequired && (
              <p className={hintCls}>With neither, they&rsquo;re admitted the moment they arrive.</p>
            )}
          </div>
        )}
      </section>

      {/* 4. Reports and shortcut — only where there is something to evaluate */}
      {hasProcess && (
        <section className="flex flex-col gap-2">
          <label className="flex flex-col gap-1">
            <span className={labelCls}>Reports needed</span>
            <input
              className={`${field} w-24`}
              type="number"
              min={1}
              max={50}
              value={lane.reportsNeeded ?? 2}
              onChange={(e) => onChange({ reportsNeeded: Number(e.target.value) || 1 })}
            />
            <span className={hintCls}>How many people have to file a report on them before it&rsquo;s decided.</span>
          </label>
          <Toggle
            label="Let members' support skip the rest"
            checked={lane.supportShortcutCount != null}
            onChange={(v) => onChange({ supportShortcutCount: v ? 3 : null })}
          />
          {lane.supportShortcutCount != null && (
            <label className="flex flex-col gap-1">
              <span className={labelCls}>Members whose support admits them</span>
              <input
                className={`${field} w-24`}
                type="number"
                min={1}
                max={50}
                value={lane.supportShortcutCount}
                onChange={(e) => onChange({ supportShortcutCount: Number(e.target.value) || 1 })}
              />
            </label>
          )}
        </section>
      )}

      {/* 5. Where it's open */}
      <section className="flex flex-col gap-1">
        <Toggle
          label="Open at the community's own door"
          checked={lane.openInCommunity}
          onChange={(v) => onChange({ openInCommunity: v })}
        />
        <p className={hintCls}>
          Off for a lane that only an event opens. Each event chooses which lanes it opens, on its own page.
        </p>
      </section>

      <div className="flex justify-between border-t border-dashed border-[var(--border)] pt-2">
        <p className="max-w-[420px] text-[length:var(--text-body)] text-[var(--text)]">
          <span className="text-[var(--text-muted)]">What happens: </span>
          {describeLaneConsequence(lane)}
        </p>
        <Button onClick={onRemove}>{lane.id ? "Archive lane" : "Discard lane"}</Button>
      </div>
    </div>
  );
}
